/** 八岐大蛇の首と頭（i 番目。前に広がる扇に八つ） */
function orochiHead(i: number): Part[] {
  const a = Math.PI / 2 + (i / 7 - 0.5) * Math.PI * 1.1;
  const h = 0.82 + (i % 2) * 0.14;
  const base: [number, number, number] = [Math.cos(a) * 0.16, 0.2, Math.sin(a) * 0.16 + 0.05];
  const head: [number, number, number] = [Math.cos(a) * 0.48, h, Math.sin(a) * 0.42 + 0.12];
  return [
    limb("#3e5236", base, head, 0.13, 0.8),
    { s: "sphere", c: "#4a6040", p: [head[0], head[1] + 0.03, head[2] + 0.05], sc: [0.17, 0.13, 0.24] },
    ...mirror((sx) => [{ s: "sphere", c: "#ffffff", p: [head[0] + sx * 0.06, head[1] + 0.08, head[2] + 0.1], sc: 0.045, glow: "red", small: true } as Part]),
  ];
}

